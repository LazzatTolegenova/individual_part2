let counter = 10;
log("Start: counter = " + counter);

counter++;
log("counter++  -> " + counter);   // +1  => 11

counter--;
log("counter--  -> " + counter);   // -1  => 10

counter += 5;
log("counter += 5 -> " + counter); // 10 + 5 => 15

counter -= 3;
log("counter -= 3 -> " + counter); // 15 - 3 => 12

counter *= 2;
log("counter *= 2 -> " + counter); // 12 * 2 => 24

counter /= 4;
log("counter /= 4 -> " + counter); // 24 / 4 => 6
